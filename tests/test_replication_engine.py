def test_composite_primary_key_resume(db_conn):
    """Test 4: Bridge tables with composite primary keys."""
    with db_conn.begin():
        db_conn.execute(text("DROP TABLE IF EXISTS test_repl_composite CASCADE;"))
        db_conn.execute(text("""
            CREATE TABLE test_repl_composite (
                prod_key INT NOT NULL,
                supp_key INT NOT NULL,
                pref_flag BOOLEAN,
                PRIMARY KEY (prod_key, supp_key)
            );
        """))

        stmt = text("""
            INSERT INTO test_repl_composite (prod_key, supp_key, pref_flag)
            VALUES (:prod_key, :supp_key, :pref_flag)
            ON CONFLICT (prod_key, supp_key) DO NOTHING;
        """)

        # Batch 1
        db_conn.execute(stmt, [
            {"prod_key": 1, "supp_key": 10, "pref_flag": True},
            {"prod_key": 1, "supp_key": 20, "pref_flag": False},
        ])
        assert db_conn.execute(text("SELECT COUNT(*) FROM test_repl_composite;")).scalar() == 2

        # Resume: Re-insert Batch 1 + new row
        db_conn.execute(stmt, [
            {"prod_key": 1, "supp_key": 10, "pref_flag": True},
            {"prod_key": 2, "supp_key": 10, "pref_flag": True},
        ])
        assert db_conn.execute(text("SELECT COUNT(*) FROM test_repl_composite;")).scalar() == 3

        db_conn.execute(text("DROP TABLE test_repl_composite CASCADE;"))


def test_idempotent_reexecution_and_sequence_sync(db_conn):
    """Test 5: Idempotent re-execution and sequence synchronization."""
    with db_conn.begin():
        db_conn.execute(text("DROP TABLE IF EXISTS test_repl_sync CASCADE;"))
        db_conn.execute(text("""
            CREATE TABLE test_repl_sync (
                item_id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                item_code VARCHAR(20) NOT NULL
            );
        """))

        stmt = text("""
            INSERT INTO test_repl_sync (item_id, item_code)
            OVERRIDING SYSTEM VALUE
            VALUES (:item_id, :item_code)
            ON CONFLICT (item_id) DO NOTHING;
        """)

        # Simulate replicating 50 items
        items = [{"item_id": i, "item_code": f"CODE_{i}"} for i in range(1, 51)]
        db_conn.execute(stmt, items)
        assert db_conn.execute(text("SELECT COUNT(*) FROM test_repl_sync;")).scalar() == 50

        # Synchronize sequence
        seq_name = db_conn.execute(text("SELECT pg_get_serial_sequence('test_repl_sync', 'item_id');")).scalar()
        assert seq_name is not None
        db_conn.execute(text(f"SELECT setval('{seq_name}', (SELECT MAX(item_id) FROM test_repl_sync));"))

        # Verify future default insert picks up at 51 without collision
        db_conn.execute(text("INSERT INTO test_repl_sync (item_code) VALUES ('NEW_ITEM');"))
        new_id = db_conn.execute(text("SELECT item_id FROM test_repl_sync WHERE item_code = 'NEW_ITEM';")).scalar()
        assert new_id == 51

        # Re-run replication batch (idempotency check)
        db_conn.execute(stmt, items)
        assert db_conn.execute(text("SELECT COUNT(*) FROM test_repl_sync;")).scalar() == 51

        db_conn.execute(text("DROP TABLE test_repl_sync CASCADE;"))
