"""
Unit & Integration Tests for OpsPulse Cloud Warehouse Replication Engine.

Tests:
1. GENERATED ALWAYS AS IDENTITY insertion with OVERRIDING SYSTEM VALUE.
2. GENERATED BY DEFAULT AS IDENTITY column insertion.
3. Tables without identity columns (standard primary keys).
4. Composite primary key tables (e.g. bridge_product_supplier).
5. Safe resume with existing partially populated target tables (idempotency, 0 duplicates).
6. Repeated execution safety.
7. Identity sequence discovery and post-replication synchronization.
8. Non-destructive preservation of target data.
"""

import pytest
from sqlalchemy import text
from warehouse.db_connection import get_database_engine


@pytest.fixture
def db_conn():
    engine = get_database_engine()
    with engine.connect() as conn:
        yield conn


def test_generated_always_identity_insertion(db_conn):
    """Test 1: GENERATED ALWAYS identity insertion requires OVERRIDING SYSTEM VALUE."""
    with db_conn.begin():
        db_conn.execute(text("DROP TABLE IF EXISTS test_repl_always CASCADE;"))
        db_conn.execute(text("""
            CREATE TABLE test_repl_always (
                key_id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
                val_text VARCHAR(50) NOT NULL,
                val_num NUMERIC(10,2)
            );
        """))

    # Attempting normal insert with explicit key_id fails in PostgreSQL
    with db_conn.begin():
        with pytest.raises(Exception):
            with db_conn.begin_nested():
                db_conn.execute(text(
                    "INSERT INTO test_repl_always (key_id, val_text, val_num) VALUES (1, 'Test', 99.9);"
                ))

        # With OVERRIDING SYSTEM VALUE it must succeed
        stmt = text("""
            INSERT INTO test_repl_always (key_id, val_text, val_num)
            OVERRIDING SYSTEM VALUE
            VALUES (:key_id, :val_text, :val_num)
            ON CONFLICT (key_id) DO NOTHING;
        """)
        db_conn.execute(stmt, [
            {"key_id": 1, "val_text": "Item 1", "val_num": 10.50},
            {"key_id": 2, "val_text": "Item 2", "val_num": 20.00},
        ])

        cnt = db_conn.execute(text("SELECT COUNT(*) FROM test_repl_always;")).scalar()
        assert cnt == 2
        db_conn.execute(text("DROP TABLE test_repl_always CASCADE;"))


def test_generated_by_default_identity(db_conn):
    """Test 2: GENERATED BY DEFAULT identity column handling."""
    with db_conn.begin():
        db_conn.execute(text("DROP TABLE IF EXISTS test_repl_default CASCADE;"))
        db_conn.execute(text("""
            CREATE TABLE test_repl_default (
                key_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                val_text VARCHAR(50) NOT NULL
            );
        """))

        stmt = text("""
            INSERT INTO test_repl_default (key_id, val_text)
            OVERRIDING SYSTEM VALUE
            VALUES (:key_id, :val_text)
            ON CONFLICT (key_id) DO NOTHING;
        """)
        db_conn.execute(stmt, [{"key_id": 10, "val_text": "Default 10"}])
        row = db_conn.execute(text("SELECT key_id, val_text FROM test_repl_default;")).fetchone()
        assert row[0] == 10
        assert row[1] == "Default 10"

        db_conn.execute(text("DROP TABLE test_repl_default CASCADE;"))


